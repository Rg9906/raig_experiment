"""
Flatten the manuscript into ONE self-contained .tex file.

The working manuscript is split across main.tex plus ten section files, which
is convenient to edit and inconvenient to submit or to paste into Overleaf.
This inlines every \\input and substitutes the generated bibliography
(main.bbl) for the \\bibliography command, so the output needs neither the
section files nor refs.bib nor a bibtex pass: one pdflatex run twice is enough.

Usage:  py make_single_file.py            (writes raig_single.tex)
        py make_single_file.py OUT.tex

Run it from paper/journal/. Requires main.bbl to exist, i.e. bibtex must have
been run at least once on main.tex.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else "raig_single.tex"

INPUT_RE = re.compile(r"^\\input\{([^}]+)\}\s*$", re.M)
BIB_RE = re.compile(r"^\\bibliographystyle\{[^}]*\}\s*\n\\bibliography\{[^}]*\}\s*$",
                    re.M)


def read(name):
    path = os.path.join(HERE, name if name.endswith(".tex") else name + ".tex")
    with io.open(path, encoding="utf-8") as f:
        return f.read()


main = read("main.tex")

# 1. Inline every \input{...}
inlined = []


def sub_input(m):
    name = m.group(1)
    inlined.append(name)
    body = read(name).rstrip("\n")
    return ("%% ---------------------------------------------------------------\n"
            "%% begin " + name + ".tex\n"
            "%% ---------------------------------------------------------------\n"
            + body +
            "\n%% end " + name + ".tex\n")


main = INPUT_RE.sub(sub_input, main)

# 2. Replace the bibliography commands with the generated thebibliography block
bbl_path = os.path.join(HERE, "main.bbl")
if not os.path.exists(bbl_path):
    sys.exit("main.bbl not found: run  pdflatex main && bibtex main  first.")
with io.open(bbl_path, encoding="utf-8") as f:
    bbl = f.read().rstrip("\n")

replaced = [False]


def sub_bib(m):
    replaced[0] = True
    return ("%% ---------------------------------------------------------------\n"
            "%% Bibliography, inlined from main.bbl so that this file compiles\n"
            "%% without bibtex and without refs.bib.\n"
            "%% ---------------------------------------------------------------\n"
            + bbl + "\n")


main = BIB_RE.sub(sub_bib, main)
if not replaced[0]:
    sys.exit("did not find the \\bibliographystyle/\\bibliography pair in main.tex")

header = (
    "%% " + "=" * 73 + "\n"
    "%% SINGLE-FILE BUILD -- generated by make_single_file.py; do not edit.\n"
    "%% Edit main.tex and the sec_*.tex sources, then regenerate.\n"
    "%%\n"
    "%% Self-contained: every \\input is inlined and the bibliography is the\n"
    "%% generated main.bbl, so this compiles with two pdflatex passes and needs\n"
    "%% no bibtex run and no other file.\n"
    "%%\n"
    "%% Inlined sections: " + ", ".join(inlined) + "\n"
    "%% " + "=" * 73 + "\n\n"
)

with io.open(os.path.join(HERE, OUT), "w", encoding="utf-8") as f:
    f.write(header + main)

n_lines = (header + main).count("\n") + 1
print("wrote %s  (%d sections inlined, %d lines, %d KB)"
      % (OUT, len(inlined), n_lines,
         os.path.getsize(os.path.join(HERE, OUT)) // 1024))
